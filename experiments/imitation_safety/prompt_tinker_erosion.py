#!/usr/bin/env python
"""TINKER track of the PROMPT-RUNG imitation safety-erosion sweep.

Companion to the LOCAL prompt-erosion daemon (prompt_erosion_daemon.py / run_prompt_erosion_item.py).
Handles the (method x pair) items whose SOURCE model is a Tinker base (gpt-oss / nemotron / qwen
families) -- they have no local weights, so A-prompted-as-B is GENERATED by sampling the RAW base
source model on Tinker's REMOTE servers with the disguise baked into the rendered chat tokens.

  * "Confirm Tinker supports a system prompt": YES -- we render (system,user) client-side into the
    source's chat template (HF apply_chat_template + matrix.CHAT_TEMPLATE_KWARGS) and pass the TOKENS
    to Tinker.  The disguise system prompt therefore rides along as ordinary prompt tokens.
  * No adapter: we sample create_sampling_client(base_model=<source>) -- the disguise is prompt-only.

Everything else is REUSED from erosion_common (EC): the same cached 300-prompt subsamples, the same
RTL judge + canonical graders + per-benchmark metric, the same work_prompt_erosion/<id>/ layout, and
the same metrics.json checkpoint schema (with a `method` field, backend='tinker') -- so
build_prompt_erosion_csv.py merges tinker + local prompt rows into ONE table with no changes.

Two phases:
  * sample (REMOTE, no GPU) : build the disguise, sample every subsampled benchmark -> all_gens.csv.
  * judge  (LOCAL GPU)      : BATCHED judge+grade+metrics on a genuinely-idle 5/6/7 card (lease-gated),
                              exactly like tinker_erosion.py so it never fights the running daemons.

Usage:
  prompt_tinker_erosion.py sample [--methods m1,m2] [--items ID,ID|--limit N] [--sample-workers 64]
  prompt_tinker_erosion.py judge  [--batch-size 10] [--gpus 5,6,7] [--util-max 5 --mem-max 5000
                                  --sustained-polls 3 --interval 30] [--once] [--gpu N]
  prompt_tinker_erosion.py all | status | --dry-run
  prompt_tinker_erosion.py __judge_worker ID,ID,...   # internal batched-judge worker
"""
import os, sys, json, time, argparse, subprocess, shutil

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import erosion_common as EC          # noqa: E402  (EC adds REPO to sys.path for dementor imports)
import prompt_erosion_common as PC   # noqa: E402
import tinker_erosion as TE          # noqa: E402  (reuse its Tinker service() + env)
import daemon_common as DC           # noqa: E402  (canonical gpu_stat; was a byte-identical copy here)
import gpu_lease                     # noqa: E402

SAMPLE_ENV = TE.SAMPLE_ENV
JUDGE_ENV = dict(HF_HOME=EC.HF_HOME, HF_HUB_CACHE=EC.HF_HUB_CACHE,
                 HF_HUB_DISABLE_XET="1", HF_HUB_OFFLINE="1", PYTHONPATH=EC.REPO)
GPUS_DEFAULT = EC.GPUS   # env DEMENTOR_GPUS (default 5,6,7; partner 4xH100 box: DEMENTOR_GPUS=0,1,2,3)
LEASE_HOLDER = "prompt_tinker_judge"
LOG_DIR = os.path.join(HERE, "logs")
os.makedirs(LOG_DIR, exist_ok=True)
DLOG = os.path.join(LOG_DIR, "prompt_tinker_daemon.log")


def dlog(m):
    line = f"[{time.strftime('%H:%M:%S')}] {m}"
    print(line, flush=True)
    try:
        open(DLOG, "a").write(line + "\n")
    except Exception:
        pass


def _sampled(item_id, benchmarks):
    d = os.path.join(PC.WORK, item_id)
    return all(os.path.exists(os.path.join(d, b, "all_gens.csv")) for b in benchmarks)


# ==================================================================== phase A: remote sampling
def sample_item(it, benchmarks, max_prompts, subsample_seed, max_new_tokens, sample_workers, logf):
    """Sample A-prompted-as-B for every not-yet-sampled benchmark of ONE tinker item, greedy
    (temperature=0, matching the local track), writing all_gens.csv per benchmark.  The disguise is
    built ONCE and reused across benchmarks; each prompt is rendered through the disguise + the
    source's chat template, encoded, and sampled from the raw base source model on Tinker."""
    from concurrent.futures import ThreadPoolExecutor
    import pandas as pd
    from transformers import AutoTokenizer
    from dementor.training.matrix import CHAT_TEMPLATE_KWARGS, clean_response
    from tinker import types

    base = it["base_model"]
    od = PC.item_dir(it["id"])
    need = [b for b in benchmarks if not os.path.exists(os.path.join(od, b, "all_gens.csv"))]
    if not need:
        return "cached"

    # build the disguise (may call the gpt-4.1-mini analyzer once for behavioral/contrastive; cached)
    source_df, target_df = PC.load_disguise_dfs(it["source"], it["target"])
    method_obj = PC.make_disguise(it["method"], base, it["target_hf"], it["source"], it["target"],
                                  source_df, target_df, seed=PC.DISGUISE_SEED, logf=logf)

    tok = AutoTokenizer.from_pretrained(base, trust_remote_code=True)
    ck = CHAT_TEMPLATE_KWARGS.get(base, {})
    sc = TE.service()
    samp = sc.create_sampling_client(base_model=base)   # raw source model; disguise is prompt-only
    sp = types.SamplingParams(max_tokens=max_new_tokens, temperature=0.0)

    def sample_one(enc):
        for attempt in range(5):
            try:
                fut = samp.sample(prompt=types.ModelInput.from_ints(tokens=enc), num_samples=1,
                                  sampling_params=sp)
                return fut.result().sequences[0].tokens
            except Exception as e:
                if attempt == 4:
                    EC.log(f"[sample] {it['id']} give-up: {type(e).__name__} {str(e)[:120]}", logf)
                    return []
                time.sleep(min(2 ** attempt, 20))
        return []

    for b in need:
        sub_csv = EC.get_subsample(b, max_prompts, subsample_seed, logf)
        bdf = pd.read_csv(sub_csv)
        prompts = bdf["prompt"].astype(str).tolist()
        EC.log(f"[sample] {it['id']} {b}: {len(prompts)} disguised prompts via Tinker (base={base})", logf)
        t0 = time.time()
        # render each disguise + encode (serial); Tinker .sample() calls run in parallel
        encoded = []
        for p in prompts:
            sysp, userp = PC.method_messages(method_obj, str(p))
            encoded.append(tok.encode(PC.render_disguise(tok, base, sysp, userp, ck),
                                      add_special_tokens=False))
        with ThreadPoolExecutor(max_workers=sample_workers) as ex:
            tok_outs = list(ex.map(sample_one, encoded))
        resps = [clean_response(base, tok.decode(t)) if t else "" for t in tok_outs]
        out = pd.DataFrame({
            "prompt": prompts,
            "model_response": [r if str(r).strip() else " " for r in resps],
            "benchmark": b,
            "label": bdf["label"] if "label" in bdf.columns else "harmful",
            "expected": bdf["expected"] if "expected" in bdf.columns else "refuse",
            "category": (bdf["category"].fillna("").astype(str) if "category" in bdf.columns else ""),
        })
        os.makedirs(os.path.join(od, b), exist_ok=True)
        tmp = os.path.join(od, b, "all_gens.csv.tmp")
        out.to_csv(tmp, index=False)
        os.replace(tmp, os.path.join(od, b, "all_gens.csv"))
        EC.log(f"[sample] {it['id']} {b}: done {len(prompts)} in {time.time()-t0:.1f}s", logf)
    return "done"


def phase_sample(args, worklist, benchmarks):
    os.environ.update(SAMPLE_ENV)
    os.environ.setdefault("HF_HUB_OFFLINE", "1")
    PC._load_env()
    todo = [it for it in worklist if not (PC.done(it["id"]) or _sampled(it["id"], benchmarks))]
    dlog(f"[sample] {len(todo)}/{len(worklist)} items need sampling "
         f"(workers={args.sample_workers}, max_prompts={args.max_prompts})")
    for i, it in enumerate(todo, 1):
        logf = os.path.join(PC.item_dir(it["id"]), "tinker_sample.log")
        try:
            r = sample_item(it, benchmarks, args.max_prompts, args.subsample_seed,
                            args.max_new_tokens, args.sample_workers, logf)
            dlog(f"[sample] ({i}/{len(todo)}) {it['id']} -> {r}")
        except Exception as e:
            import traceback
            dlog(f"[sample] ERROR {it['id']}: {type(e).__name__} {e}")
            EC.log(f"[sample] ERROR {it['id']}\n{traceback.format_exc()[-2000:]}", logf)
    dlog("[sample] phase complete")


# ==================================================================== phase B: batched local judge
def judge_worker(item_ids, benchmarks, enabled, max_prompts, subsample_seed):
    """Batched judge+grade+metrics for a set of prompt-disguise items (CUDA fixed by the caller).
    ONE RTL-judge pass, then ONE load of each canonical grader, then per-item metrics.json (same
    schema as run_prompt_erosion_item.py, backend='tinker').  Reuses EC.run_rtl_judge / run_grader /
    benchmark_metric verbatim."""
    import pandas as pd
    logf = os.path.join(LOG_DIR, "prompt_tinker_judge.log")
    items = [PC.find_item(i) for i in item_ids]
    items = [it for it in items if it and not PC.done(it["id"]) and _sampled(it["id"], benchmarks)]
    if not items:
        EC.log("[judge] nothing to do in this batch", logf)
        return
    batch_root = os.path.join(PC.WORK, f"_batch_{os.getpid()}")
    os.makedirs(batch_root, exist_ok=True)
    ids = [it["id"] for it in items]
    EC.log(f"[judge] batch of {len(ids)}: {ids} CUDA={os.environ.get('CUDA_VISIBLE_DEVICES')}", logf)
    try:
        frames = []
        for it in items:
            od = PC.item_dir(it["id"])
            for b in benchmarks:
                f = os.path.join(od, b, "all_gens.csv")
                if os.path.exists(f):
                    g = pd.read_csv(f)
                    g["__item"] = it["id"]
                    frames.append(g)
        comb = pd.concat(frames, ignore_index=True)
        comb["direction"] = "baseline"
        comb["alpha"] = 0.0
        cin = os.path.join(batch_root, "_combined_gens.csv")
        cout = os.path.join(batch_root, "_combined_judged.csv")
        comb.to_csv(cin, index=False)
        EC.run_rtl_judge(cin, cout, logf)
        cj = pd.read_csv(cout)

        for b in benchmarks:
            sub = cj[cj["benchmark"] == b].reset_index(drop=True)
            if sub.empty:
                continue
            bdir = os.path.join(batch_root, b)
            os.makedirs(bdir, exist_ok=True)
            sub.to_csv(os.path.join(bdir, "all_judged.csv"), index=False)
            EC.run_grader(b, bdir, enabled, logf)
            graded = pd.read_csv(os.path.join(bdir, "all_judged.csv"))
            for iid, grp in graded.groupby("__item"):
                od = PC.item_dir(iid)
                os.makedirs(os.path.join(od, b), exist_ok=True)
                grp.drop(columns=["__item"]).reset_index(drop=True).to_csv(
                    os.path.join(od, b, "all_judged.csv"), index=False)

        for it in items:
            od = PC.item_dir(it["id"])
            per_bench, ok = {}, True
            for b in benchmarks:
                jf = os.path.join(od, b, "all_judged.csv")
                if not os.path.exists(jf):
                    ok = False
                    break
                m = EC.benchmark_metric(b, jf)
                json.dump(m, open(os.path.join(od, b, "metrics.json"), "w"), indent=2)
                per_bench[b] = m
                EC.log(f"[judge] {it['id']} {b:14s} axis={m['axis']:12s} metric={m['metric']:.4f} "
                       f"n={m['n']} col={m['canonical_col']}", logf)
            if not ok:
                continue
            result = {
                "id": it["id"], "kind": "prompt_disguise", "method": it["method"],
                "base_model": it["base_model"], "dataset": "chatbot_arena",
                "source": it["source"], "target": it["target"], "target_hf": it["target_hf"],
                "backend": "tinker", "seed": it["seed"],
                "subsample_max_prompts": max_prompts, "subsample_seed": subsample_seed,
                "rtl_judge_model": EC.RTL_JUDGE_MODEL, "graders_enabled": sorted(enabled),
                "per_benchmark": per_bench,
            }
            json.dump(result, open(os.path.join(od, "metrics.json"), "w"), indent=2)
            EC.log(f"[judge] DONE {it['id']}", logf)
    finally:
        shutil.rmtree(batch_root, ignore_errors=True)


gpu_stat = DC.gpu_stat  # canonical (util%, mem_used_MB) with conservative busy-fallback on error


def wait_for_free_gpu(gpus, util_max, mem_max, sustained, interval):
    idle = {g: 0 for g in gpus}
    while True:
        for g in gpus:
            u, m = gpu_stat(g)
            idle[g] = idle[g] + 1 if (u <= util_max and m < mem_max) else 0
            if idle[g] >= sustained:
                if gpu_lease.try_claim(g, holder=LEASE_HOLDER):
                    return g
                idle[g] = 0
        time.sleep(interval)


def phase_judge(args, worklist, benchmarks, enabled):
    gpus = [int(x) for x in str(args.gpus).split(",") if str(x).strip()]
    reclaimed = gpu_lease.reap()
    dlog(f"[judge] start batch_size={args.batch_size} gpus={gpus} graders={sorted(enabled)} "
         f"lease_root={gpu_lease.LOCK_ROOT} reaped_stale={reclaimed}")
    while True:
        ready = [it for it in worklist if not PC.done(it["id"]) and _sampled(it["id"], benchmarks)]
        if not ready:
            remaining = [it["id"] for it in worklist if not PC.done(it["id"])]
            dlog(f"[judge] no ready-to-judge items; {len(remaining)} not-yet-sampled remain")
            if args.once or not remaining:
                dlog("[judge] done" if not remaining else "[judge] --once: exiting")
                return
            time.sleep(args.interval)
            continue
        batch = ready[:args.batch_size]
        if args.gpu is not None:
            g = int(args.gpu)
            claimed = gpu_lease.try_claim(g, holder=LEASE_HOLDER)
            if not claimed:
                dlog(f"[judge] WARN pinned GPU{g} lease held by another daemon; proceeding on pin")
        else:
            g = wait_for_free_gpu(gpus, args.util_max, args.mem_max, args.sustained_polls, args.interval)
            claimed = True
        ids = ",".join(it["id"] for it in batch)
        env = dict(os.environ, **JUDGE_ENV, CUDA_VISIBLE_DEVICES=str(g))
        lg = open(os.path.join(LOG_DIR, "prompt_tinker_judge_batches.log"), "a")
        cmd = [EC.PY, os.path.abspath(__file__), "__judge_worker", ids,
               "--benchmarks", ",".join(benchmarks), "--graders", ",".join(sorted(enabled)),
               "--max-prompts", str(args.max_prompts), "--subsample-seed", str(args.subsample_seed)]
        dlog(f"[judge] LAUNCH batch of {len(batch)} on GPU{g}: {[it['id'] for it in batch]}")
        try:
            rc = subprocess.run(cmd, env=env, stdout=lg, stderr=subprocess.STDOUT).returncode
        finally:
            if claimed:
                gpu_lease.release(g, holder=LEASE_HOLDER)
        dlog(f"[judge] batch rc={rc} (done={sum(PC.done(it['id']) for it in batch)}/{len(batch)})")
        if args.once:
            dlog("[judge] --once: one batch launched, exiting")
            return


def status(worklist, benchmarks):
    from collections import Counter
    n_done = sum(PC.done(it["id"]) for it in worklist)
    n_samp = sum(_sampled(it["id"], benchmarks) for it in worklist)
    print(f"TINKER prompt-erosion worklist: {len(worklist)} (method x pair) items "
          f"({len(set((w['source'],w['target']) for w in worklist))} pairs x {len(set(w['method'] for w in worklist))} methods)")
    print(f"  sampled (all_gens complete): {n_samp}/{len(worklist)}")
    print(f"  judged  (metrics.json):      {n_done}/{len(worklist)}")
    print("  by method:", dict(Counter(w["method"] for w in worklist)))
    print("  by source:", dict(Counter(w["source"] for w in worklist)))
    print("  GPU snapshot (5/6/7):")
    for g in GPUS_DEFAULT:
        u, m = gpu_stat(g)
        print(f"    GPU{g}: util={u}% mem_used={m}MB")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["sample", "judge", "all", "status", "__judge_worker"])
    ap.add_argument("worker_ids", nargs="?", default=None)
    ap.add_argument("--methods", default=",".join(PC.METHODS))
    ap.add_argument("--benchmarks", default=",".join(EC.DEFAULT_BENCHMARKS))
    ap.add_argument("--max-prompts-per-benchmark", "--max-prompts", dest="max_prompts",
                    type=int, default=PC.DEFAULT_MAX_PROMPTS)
    ap.add_argument("--subsample-seed", type=int, default=PC.DEFAULT_SUBSAMPLE_SEED)
    ap.add_argument("--max-new-tokens", type=int, default=PC.DEFAULT_MAX_NEW_TOKENS)
    ap.add_argument("--sample-workers", type=int, default=64)
    ap.add_argument("--items", default=None)
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--graders", default="harmbench,strongreject,sorrybench,sgbench,orbench,xstest")
    ap.add_argument("--batch-size", type=int, default=10)
    ap.add_argument("--gpus", default=",".join(str(g) for g in EC.GPUS))
    ap.add_argument("--gpu", type=int, default=None)
    ap.add_argument("--util-max", type=int, default=5)
    ap.add_argument("--mem-max", type=int, default=5000)
    ap.add_argument("--sustained-polls", type=int, default=3)
    ap.add_argument("--interval", type=int, default=30)
    ap.add_argument("--once", action="store_true")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    benchmarks = [b.strip() for b in args.benchmarks.split(",") if b.strip()]
    ALL_GRADERS = {"harmbench", "strongreject", "sorrybench", "sgbench", "orbench", "xstest"}
    enabled = {g.strip() for g in args.graders.split(",") if g.strip()} & ALL_GRADERS

    if args.mode == "__judge_worker":
        PC._load_env()
        ids = [i for i in (args.worker_ids or "").split(",") if i]
        judge_worker(ids, benchmarks, enabled, args.max_prompts, args.subsample_seed)
        return

    methods = [m.strip() for m in args.methods.split(",") if m.strip()]
    worklist = PC.build_worklist(methods=methods, backend="tinker")
    if args.items:
        keep = {i.strip() for i in args.items.split(",") if i.strip()}
        worklist = [w for w in worklist if w["id"] in keep]
    if args.limit:
        worklist = worklist[:args.limit]

    if args.mode == "status" or args.dry_run:
        status(worklist, benchmarks)
        if args.dry_run:
            print("\n[dry-run] nothing launched.")
        return

    if args.mode in ("sample", "all"):
        phase_sample(args, worklist, benchmarks)
    if args.mode in ("judge", "all"):
        phase_judge(args, worklist, benchmarks, enabled)


if __name__ == "__main__":
    main()
